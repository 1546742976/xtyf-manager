'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {spawn}=require('node:child_process');
const {chromium,webkit,devices,request}=require('playwright');
const {recordFailure,cleanupResources}=require('./diagnostics.cjs');
const root=path.resolve(__dirname,'../..'),output=path.join(root,'.build-tools/assets-serialized-check');
fs.mkdirSync(output,{recursive:true});
const server=spawn(process.env.REVIEW_PYTHON||'python',['-B','tests/browser/server.py'],{cwd:root,env:{...process.env,MAIL_MODE:'preview'},stdio:['ignore','pipe','pipe']});
let browser,page,api,engineName;const errors=[],passed=[];
async function main(){
  const base=await new Promise((resolve,reject)=>{let log='';const timer=setTimeout(()=>reject(Error(log)),30000);server.stderr.on('data',d=>log+=d);server.stdout.on('data',d=>{log+=d;const m=log.match(/BROWSER_URL=(\S+)/);if(m){clearTimeout(timer);resolve(m[1]);}});server.once('exit',c=>{clearTimeout(timer);reject(Error(c+' '+log));});});
  api=await request.newContext({baseURL:base});let csrf=(await(await api.get('/api/csrf')).json()).csrf_token;
  async function post(url,data){const r=await api.post(url,{headers:{'X-CSRF-Token':csrf},data});csrf=r.headers()['x-csrf-token']||csrf;assert.equal(r.status(),200,await r.text());return r.json();}
  await post('/api/client/login',{username:'admin',password:'browser-test-initial'});
  await post('/api/password',{old:'browser-test-initial',new:'serialized-browser-password',confirm:'serialized-browser-password'});
  const campus=(await post('/api/assets/catalog/campuses',{request_id:crypto.randomUUID(),name:'合成校区'})).id;
  for(const [label,engine,options] of [['chromium',chromium,{viewport:{width:1280,height:900}}],['webkit',webkit,devices['iPhone 13']]]){
    engineName=label;browser=await engine.launch();
    const context=await browser.newContext({...options,storageState:await api.storageState()});
    page=await context.newPage();page.setDefaultTimeout(15000);page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base+'/assets');await page.locator('#asset-status').filter({hasText:'数据已更新'}).waitFor();
    await page.locator('#asset-create').click();
    await page.locator('#asset-add-manual').click();
    await page.getByLabel('名称',{exact:true}).fill('不应提交的草稿');
    await page.locator('#asset-close').click();
    await page.locator('#asset-add-dialog[open]').waitFor();
    await page.locator('#asset-add-close').click();
    await page.locator('#asset-add-dialog').waitFor({state:'hidden'});
    const created=await post('/api/assets/catalog/items',{
      request_id:crypto.randomUUID(),name:'逐件测试 '+label,kind:'returnable',unit:'台'
    });
    const id=created.id;
    await page.goto(base+'/assets/detail?id='+id);
    await page.locator('#asset-status').filter({hasText:'数据已更新'}).waitFor();
    await page.getByRole('button',{name:'管理单件',exact:true}).click();
    await page.locator('#asset-unit-drawer[open]').waitFor();
    await page.locator('#asset-unit-content [data-unit-action=receive]').click();
    await page.locator('#asset-form [name=campus_id]').selectOption(String(campus));
    await page.locator('#asset-form [name=quantity]').fill('3');
    await page.locator('#asset-form [name=reason]').fill('合成实物入库');
    await page.locator('#asset-save').click();await page.locator('#asset-dialog').waitFor({state:'hidden'});
    const received=await(await api.get('/api/assets/units?item_id='+id)).json();
    assert.equal(received.units.length,3,'receipt must persist three physical identities');
    await page.locator('#asset-unit-drawer[open]').waitFor();
    await page.locator('#asset-unit-content [data-unit-select]').first().waitFor();
    assert.equal(await page.locator('#asset-unit-content [data-unit-select]').count(),3,'resumed drawer must refresh received units');
    await page.locator('#asset-unit-content [data-unit-select]').nth(0).check();
    await page.locator('#asset-unit-content [data-unit-select]').nth(1).check();
    await page.locator('#asset-unit-actions [data-unit-action=borrow]').click();
    await page.locator('#asset-form [name=reason]').fill('合成借用');
    let lost=true;
    await page.route('**/api/assets/units/operate',async route=>{
      if(lost){lost=false;await route.fetch();await route.abort();}else await route.continue();
    });
    await page.locator('#asset-save').click();
    await page.locator('#asset-form-status').filter({hasText:'结果尚未确认'}).waitFor();
    await page.unroute('**/api/assets/units/operate');
    await page.locator('#asset-save').click();
    await page.locator('#asset-dialog').waitFor({state:'hidden'});
    let units=(await(await api.get('/api/assets/units?item_id='+id)).json()).units;
    assert.equal(units.filter(u=>u.keeper_id).length,2);
    await page.locator('#asset-unit-drawer[open]').waitFor();
    await page.waitForFunction(()=>document.querySelector('#asset-unit-drawer').getAttribute('aria-busy')==='false');
    const free=units.find(u=>!u.keeper_id);
    await page.locator('[data-unit-select="'+free.id+'"]').check();
    await page.locator('#asset-unit-actions [data-unit-action=print]').click();
    await page.locator('#asset-label-download').waitFor({state:'visible'});
    const pdf=await api.get(await page.locator('#asset-label-download').getAttribute('href'));
    assert.equal(pdf.headers()['content-type'],'application/pdf');
    assert((await pdf.body()).subarray(0,4).equals(Buffer.from('%PDF')));
    await page.locator('#asset-label-close').click();
    await page.locator('#asset-unit-drawer[open]').waitFor();
    await page.locator('#asset-unit-close').click();
    await page.locator('#asset-scan-general').click();
    await page.locator('#asset-scan-mode').selectOption('borrow');
    await page.locator('#asset-scan-raw').fill('U:'+free.id);
    await page.locator('#asset-scan-raw').press('Enter');
    await page.locator('#asset-scan-queue [data-scan-action=submit-units]').waitFor();
    units=(await(await api.get('/api/assets/units?item_id='+id)).json()).units;
    assert.equal(units.find(u=>u.id===free.id).keeper_id,null,'scan is read-only before confirmation');
    await page.locator('#asset-scan-queue [data-scan-action=submit-units]').click();
    await page.locator('#asset-form [name=reason]').fill('合成扫码借用');
    await page.locator('#asset-save').click();await page.locator('#asset-dialog').waitFor({state:'hidden'});
    units=(await(await api.get('/api/assets/units?item_id='+id)).json()).units;
    assert.equal(units.filter(u=>u.keeper_id).length,3);
    await page.locator('#asset-scan-close').click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),true);
    await page.screenshot({path:path.join(output,label+'.png'),fullPage:true});
    passed.push(label+': dialog return, unit receive, lost-response retry, PDF labels and scan confirmation');
    await browser.close();browser=null;
  }
  assert.deepEqual(errors,[]);fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({ok:true,passed,nativeHardware:false},null,2));console.log(JSON.stringify({ok:true,passed}));
}
main().catch(async e=>{await recordFailure(e,{output,page,engine:engineName,phase:'serialized',passed,pageErrors:errors});console.error(e);process.exitCode=1;}).finally(()=>cleanupResources({browser:()=>browser?.close(),api:()=>api?.dispose(),server:()=>server.kill()}));
